local _tl_compat; if (tonumber((_VERSION or ''):match('[%d.]*$')) or 0) < 5.3 then local p, m = pcall(require, 'compat53.module'); if p then _tl_compat = m end end; local assert = _tl_compat and _tl_compat.assert or assert; local io = _tl_compat and _tl_compat.io or io; local ipairs = _tl_compat and _tl_compat.ipairs or ipairs; local os = _tl_compat and _tl_compat.os or os; local pcall = _tl_compat and _tl_compat.pcall or pcall; local string = _tl_compat and _tl_compat.string or string; local table = _tl_compat and _tl_compat.table or table




local common = require("tlcli.common")
local driver = require("tlcli.driver")
local perf = require("tlcli.perf")
local report = require("tlcli.report")
local lfs = require("lfs")








local mkdir_cache = {}

local function make_dir_for(pathname)
   local normalized, root = common.normalize(pathname)
   local dirname = normalized:match("^(.*" .. common.sep .. ")[^" .. common.sep .. "]+$")

   if dirname == root then
      return
   end
   if dirname then
      if mkdir_cache[dirname] then
         return
      end
      make_dir_for(dirname)
      lfs.mkdir(dirname)
      mkdir_cache[dirname] = true
   end
end

local function write_out(tlconfig, output_file, code, tree)
   local is_stdout = output_file == "-"
   local prettyname = is_stdout and "<stdout>" or output_file
   if tlconfig["pretend"] then
      print("Would Write: " .. prettyname)
      return
   end

   local ofd, err
   if is_stdout then
      ofd = io.output()
   else
      if tree then
         make_dir_for(output_file)
      end
      ofd, err = io.open(output_file, "wb")
      if not ofd then
         common.die("cannot write " .. prettyname .. ": " .. err)
      end
   end

   local _
   _, err = ofd:write(code, "\n")
   if err then
      common.die("error writing " .. prettyname .. ": " .. err)
   end

   if not is_stdout then
      ofd:close()
   end

   if not tlconfig["quiet"] and (not is_stdout or tlconfig["gen_target"] ~= "c") then
      print("Wrote: " .. prettyname)
   end
end










local function generated_file(path)
   if lfs.symlinkattributes(path, "mode") ~= "file" then return false end
   local fd = io.open(path, "rb")
   if not fd then return false end
   local first = fd:read("*l")
   fd:close()
   return first == "/* Generated by Teal's experimental C target. */"
end

local function io_check(ok, path, err)
   if not ok then error(path .. ": " .. tostring(err), 0) end
end

local function publish_project(tlconfig, path, dir, output, tree)
   local updates = {}
   local current = {}
   if output.header then
      table.insert(updates, { path = dir .. common.sep .. "abi.h", code = output.header })
      current["abi.h"] = true
   end
   for _, unit in ipairs(output.modules) do
      table.insert(updates, { path = dir .. common.sep .. unit.filename, code = unit.code })
      current[unit.filename] = true
   end

   if tlconfig["pretend"] then
      for _, file in ipairs(updates) do print("Would Write: " .. file.path) end
      print("Would Write: " .. path)
      return
   end
   if tree then make_dir_for(path) end



   local staging = dir .. ".stage"
   local created, mkdir_err = lfs.mkdir(staging)
   if not created then common.die("cannot stage C output in " .. staging .. ": " .. mkdir_err) end
   local made_dir = false

   local ok, err = pcall(function()
      local mode = lfs.symlinkattributes(dir, "mode")
      if not mode then
         local made, make_err = lfs.mkdir(dir)
         io_check(made, dir, make_err)
         made_dir = true
      elseif mode ~= "directory" then
         error(dir .. ": expected a C module output directory", 0)
      end
      for name in lfs.dir(dir) do
         if name == "abi.h" or name:match("^tl_[%w_-]+%.c$") then
            local existing = dir .. common.sep .. name
            if not generated_file(existing) then error(existing .. ": expected a generated C file", 0) end
            if not current[name] then table.insert(updates, { path = existing }) end
         end
      end
      table.insert(updates, { path = path, code = output.entry })

      for i, file in ipairs(updates) do
         local stem = staging .. common.sep .. tostring(i)
         file.backup = stem .. ".old"
         if file.code then
            file.staged = stem .. ".new"
            local fd, open_err = io.open(file.staged, "wb")
            io_check(fd ~= nil, file.staged, open_err)
            local written, write_err = fd:write(file.code, "\n")
            local closed, close_err = fd:close()
            io_check(written ~= nil, file.staged, write_err)
            io_check(closed, file.staged, close_err)
         end
      end

      for _, file in ipairs(updates) do
         local mode_at_path = lfs.symlinkattributes(file.path, "mode")
         if mode_at_path then
            if mode_at_path ~= "file" then error(file.path .. ": expected a regular file", 0) end
            local saved, save_err = os.rename(file.path, file.backup)
            io_check(saved, file.path, save_err)
            file.saved = true
         end
         if file.staged then
            local installed, install_err = os.rename(file.staged, file.path)
            io_check(installed, file.path, install_err)
            file.installed = true
         end
      end
   end)

   local rollback_failed = false
   for i = #updates, 1, -1 do
      local file = updates[i]
      if not ok then
         if file.installed and not os.remove(file.path) then rollback_failed = true end
         if file.saved and not os.rename(file.backup, file.path) then rollback_failed = true end
      elseif file.saved then
         os.remove(file.backup)
      end
      if file.staged then os.remove(file.staged) end
   end
   if not rollback_failed then lfs.rmdir(staging) end
   if (not ok and made_dir) or (ok and not output.header) then lfs.rmdir(dir) end
   if not ok then
      local detail = rollback_failed and (". Previous outputs remain in " .. staging) or ""
      common.die("cannot write C output: " .. tostring(err) .. detail)
   end
   if not tlconfig["quiet"] then
      for _, file in ipairs(updates) do
         if file.code then print("Wrote: " .. file.path) end
      end
   end
end

local function write_c(tlconfig, module, path, tree)
   local name = path:match("[^/\\]+$") or path
   local stem = name:gsub("%.[^.]+$", "")
   if stem == "" then stem = name end
   local module_directory = stem .. ".modules"
   if module_directory == name then module_directory = name .. ".modules" end
   local output, err = module:gen_c(module_directory)
   if not output then common.die(err) end
   if output.header and path == "-" then
      common.die("C programs with Teal imports require a file output path")
   end

   local dir = path:sub(1, #path - #name) .. module_directory
   if output.header or (path ~= "-" and lfs.symlinkattributes(dir, "mode") == "directory" and
      generated_file(dir .. common.sep .. "abi.h")) then
      publish_project(tlconfig, path, dir, output, tree)
   else
      write_out(tlconfig, path, output.entry, tree)
   end
end

return function(tlconfig, args)
   local native = tlconfig["gen_target"] == "c"
   if native then
      if #args["file"] ~= 1 then common.die("the C target requires a single Teal input file as its entry point") end
      if args["no_check"] then common.die("--no-check is incompatible with the C target") end
   end
   local ext = args["custom_ext"] or (native and ".c" or ".lua")
   if args["output"] and #args["file"] ~= 1 then
      print("Error: --output can only be used to map one input to one output")
      os.exit(1)
   end

   perf.turbo(true)

   local mods = {}
   local compiler = driver.setup_compiler(tlconfig)
   local gen_opts = {
      preserve_indent = true,
      preserve_newlines = true,
      preserve_hashbang = args["keep_hashbang"],
   }

   for i, input_file in ipairs(args["file"]) do
      local module, check_err, err = driver.process_module(compiler, input_file)
      if err then
         common.die(err)
      end

      table.insert(mods, {
         input_file = input_file,
         output_file = common.get_output_filename(input_file, args["root"], args["output_dir"], ext),
         module = module,
         check_err = check_err,
      })

      perf.check_collect(i)
   end

   for _, mod in ipairs(mods) do
      local err = mod.check_err
      if #err.syntax_errors == 0 and (args["no_check"] or #err.type_errors == 0) then
         local output_filename = args["output"] or mod.output_file
         assert(mod.module)
         local tree = not not args["root"]
         if native then
            write_c(tlconfig, mod.module, output_filename, tree)
         else
            local code, gen_error = mod.module:gen(gen_opts)
            if not code then common.die(gen_error) end
            write_out(tlconfig, output_filename, code, tree)
         end
      end
   end

   local ok = report.report_all_errors(tlconfig, compiler, args["no_check"])

   os.exit(ok and 0 or 1)
end
