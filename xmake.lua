local standalone = os.projectdir() == os.scriptdir()

rule("tl")
   set_extensions(".tl")
   on_load("extras.xmake.build.load")
   before_build("extras.xmake.build.prepare")
   on_buildcmd_file("extras.xmake.build.compile_file")
   before_run("extras.xmake.build.runenv")
   before_test("extras.xmake.build.runenv")
rule_end()

rule("tl.compiler")
   set_extensions(".tl")
   on_load("extras.xmake.build.load_compiler")
   before_build("extras.xmake.build.prepare_noconfig")
   on_buildcmd_file("extras.xmake.build.compile_bootstrap_file")
   after_buildcmd("extras.xmake.build.bundle_compiler")
rule_end()

target("tl")
   set_kind("object")
   set_default(standalone)
   set_policy("build.fence", true)
   add_rules("tl.compiler")
   add_files("teal/**.tl", "tlcli/**.tl", "precompiler.tl", "extras/combine.tl")
   on_run("extras.xmake.build.run_compiler")
target_end()

target("tl.auxlib")
   set_kind("object")
   set_default(standalone)
   add_rules("tl")
   set_values("tl.root", "extras")
   add_files("extras/auxlib/**.tl")
target_end()
